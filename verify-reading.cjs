const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const src=fs.readFileSync('js/app.js','utf8');
const ctx=vm.createContext({document:{addEventListener(){}},esc:s=>String(s??''),uid:()=> 'id',tTime:t=>[t.start,t.end].join('–'),kistList:()=>[{id:'K1',level:4,title:'第一課',strategy:'摘要'},{id:'K2',level:5,title:'第二課'}]});
